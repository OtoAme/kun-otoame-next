import { spawnSync } from 'node:child_process'
import { PrismaPg } from '@prisma/adapter-pg'
import { PrismaClient } from '@prisma/client'
import pg from 'pg'
import { afterAll, beforeAll, describe, expect, it } from 'vitest'
import {
  processResourceFileCleanup,
  queueResourceFileCleanup
} from '~/lib/resourceFileCleanup'

/**
 * Real PostgreSQL proof for cleanup reference identity and the re-queue claim.
 * Skipped unless KUN_OFFICIAL_MIRROR_A_REF_DATABASE_URL points at a disposable
 * database on 127.0.0.1 other than port 5432. Object deletion is a stub.
 */
const databaseUrl = process.env.KUN_OFFICIAL_MIRROR_A_REF_DATABASE_URL?.trim()
const container = process.env.KUN_OFFICIAL_MIRROR_A_REF_PG_CONTAINER?.trim()
const hash = 'cd'.repeat(32)
const objectKey = `patch/12/resource/${hash}/file.zip`
const spacedKey = `patch/12/resource/${hash}/my file.zip`
const publicBase = 'https://cdn.example.test'
const oldBase = 'https://old.example.test'
const bases = [publicBase, oldBase]

const forbiddenName = /touchgal|otoame_prod|postgres|template0|template1/i

describe.skipIf(!databaseUrl)('official mirror cleanup references on disposable Postgres', () => {
  if (!databaseUrl || !container) return
  const parsed = new URL(databaseUrl)
  const databaseName = decodeURIComponent(parsed.pathname.replace(/^\//, ''))
  if (parsed.hostname !== '127.0.0.1' || !parsed.port || parsed.port === '5432') {
    throw new Error('cleanup reference database must be 127.0.0.1 on a port other than 5432')
  }
  if (!databaseName || forbiddenName.test(databaseName)) {
    throw new Error('cleanup reference database name is not disposable')
  }
  if (!/^[A-Za-z0-9][A-Za-z0-9_.-]*$/.test(container)) {
    throw new Error('cleanup reference container name is not usable')
  }

  const pool = new pg.Pool({
    connectionString: databaseUrl,
    max: 2,
    connectionTimeoutMillis: 5000
  })
  const prisma = new PrismaClient({
    adapter: new PrismaPg(
      new pg.Pool({ connectionString: databaseUrl, max: 4, connectionTimeoutMillis: 5000 })
    )
  })

  const reset = async () => {
    const extras = await pool.query<{ relname: string }>(`
      SELECT c.relname
      FROM pg_class AS c
      JOIN pg_namespace AS n ON n.oid = c.relnamespace
      WHERE n.nspname = 'public'
        AND c.relkind = 'r'
        AND c.relname NOT IN ('patch_resource_link', 'patch_resource_file_cleanup')
    `)
    if (extras.rows.length > 0) {
      throw new Error(`refusing to reset a database that already has ${extras.rows.map((row) => row.relname).join(', ')}`)
    }
    await pool.query(`
      DROP TABLE IF EXISTS public.patch_resource_link;
      DROP TABLE IF EXISTS public.patch_resource_file_cleanup;
      CREATE TABLE public.patch_resource_link (
        id INTEGER PRIMARY KEY,
        content TEXT NOT NULL
      );
      CREATE TABLE public.patch_resource_file_cleanup (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        object_key VARCHAR(1007) NOT NULL UNIQUE,
        resource_id INTEGER NOT NULL,
        status VARCHAR(16) NOT NULL,
        failure_category VARCHAR(64),
        created TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
      );
    `)
  }

  beforeAll(async () => {
    const published = spawnSync('docker', ['port', container, '5432/tcp'], { encoding: 'utf8' })
    expect(published.status, published.stderr).toBe(0)
    expect(published.stdout).toContain(`${parsed.hostname}:${parsed.port}`)
    await reset()
  })

  afterAll(async () => {
    await prisma.$disconnect()
    await pool.end()
  })

  it('does not delete an object that a signed or encoded link still references', async () => {
    await reset()
    const signed = `${publicBase}/${objectKey}?token=secret-token`
    const encoded = `${oldBase}/${spacedKey.split('/').map((segment) => encodeURIComponent(segment)).join('/')}?token=secret-token#fragment`
    await pool.query(
      `INSERT INTO public.patch_resource_link (id, content) VALUES (1, $1), (2, $2)`,
      [signed, encoded]
    )
    await queueResourceFileCleanup(prisma, {
      resourceId: 12,
      publicBases: bases,
      links: [
        { storage: 's3', content: signed },
        { storage: 's3', content: spacedKey }
      ]
    })
    const deleted: string[] = []
    const report = await processResourceFileCleanup(prisma, {
      publicBases: bases,
      deleteObject: async (key) => {
        deleted.push(key)
        return 'deleted'
      }
    })
    expect(deleted).toEqual([])
    expect(report.cancelled).toBe(2)
    expect(report.completed).toBe(0)
    const statuses = await pool.query<{ status: string }>(
      `SELECT status FROM public.patch_resource_file_cleanup ORDER BY object_key`
    )
    expect(statuses.rows.map((row) => row.status)).toEqual(['cancelled', 'cancelled'])
  })

  it('does not delete when the only live reference uses a mixed percent-encoding', async () => {
    await reset()
    const mixed = `  https://CDN.example.test/patch/12/resource/${hash}/fi%6ce.zip?token=secret-token#fragment  `
    await pool.query(`INSERT INTO public.patch_resource_link (id, content) VALUES (1, $1)`, [
      mixed
    ])
    await queueResourceFileCleanup(prisma, {
      resourceId: 12,
      publicBases: bases,
      links: [{ storage: 's3', content: objectKey }]
    })
    const deleted: string[] = []
    const report = await processResourceFileCleanup(prisma, {
      publicBases: bases,
      deleteObject: async (key) => {
        deleted.push(key)
        return 'deleted'
      }
    })
    expect(deleted).toEqual([])
    expect(report.cancelled).toBe(1)
    expect(report.completed).toBe(0)
  })

  it('deletes when the only similar content is another host or a longer file name', async () => {
    await reset()
    await pool.query(
      `INSERT INTO public.patch_resource_link (id, content) VALUES (1, $1), (2, $2)`,
      [`https://evil.example.test/${objectKey}?token=secret-token`, `${publicBase}/${objectKey}-extra`]
    )
    await queueResourceFileCleanup(prisma, {
      resourceId: 12,
      publicBases: bases,
      links: [{ storage: 's3', content: objectKey }]
    })
    const deleted: string[] = []
    const report = await processResourceFileCleanup(prisma, {
      publicBases: bases,
      deleteObject: async () => {
        deleted.push('once')
        return 'deleted'
      }
    })
    expect(deleted).toEqual(['once'])
    expect(report.completed).toBe(1)
  })

  it('does not mark completed after a re-queue changes the row during delete', async () => {
    await reset()
    await queueResourceFileCleanup(prisma, {
      resourceId: 12,
      publicBases: bases,
      links: [{ storage: 's3', content: objectKey }]
    })
    const report = await processResourceFileCleanup(prisma, {
      publicBases: bases,
      deleteObject: async () => {
        await queueResourceFileCleanup(prisma, {
          resourceId: 13,
          publicBases: bases,
          links: [{ storage: 's3', content: objectKey }]
        })
        return 'deleted'
      }
    })
    expect(report.completed).toBe(0)
    const row = await pool.query<{ status: string; resource_id: number }>(
      `SELECT status, resource_id FROM public.patch_resource_file_cleanup`
    )
    expect(row.rows).toEqual([{ status: 'pending', resource_id: 13 }])
  })
})
